/**
 * Generates supabase/migrations/20261025000002_seed_exercise_library.sql from src/data/seed/exercises.ts.
 *
 * The app seeds the built-in library locally with deterministic ids (uuid v5 of the seed key) and never pushes it.
 * The server therefore needs the same rows (user_id NULL) so that synced sets/planned exercises satisfy their foreign keys.
 * Idempotent: re-running the migration or generating again never duplicates or breaks anything.
 *
 *   npm run gen:seed
 */
import { writeFileSync } from 'node:fs';
import { SEED_ROWS } from '../src/data/seed/exercises';

const q = (v: string | null): string => (v === null ? 'null' : `'${v.replace(/'/g, "''")}'`);
const arr = (v: string[]): string => `'{${v.map((x) => `"${x.replace(/(["\\])/g, '\\$1')}"`).join(',')}}'`;
const uuidArr = (v: string[]): string => (v.length ? `'{${v.join(',')}}'::uuid[]` : `'{}'::uuid[]`);
const num = (v: number | null): string => (v === null ? 'null' : String(v));

const cols = ['id', 'user_id', 'seed_key', 'name', 'aliases', 'category', 'primary_muscles', 'secondary_muscles', 'movement_pattern', 'equipment', 'laterality', 'resistance_type', 'tracking_method', 'load_mode', 'bodyweight_fraction', 'technique', 'cues', 'default_tempo', 'default_rest_s', 'difficulty', 'substitute_ids', 'is_custom', 'seed_version'] as const;

const values = SEED_ROWS.map((e) => `(${[
  q(e.id), 'null', q(e.seed_key), q(e.name), arr(e.aliases), q(e.category), arr(e.primary_muscles), arr(e.secondary_muscles), q(e.movement_pattern), q(e.equipment), q(e.laterality), q(e.resistance_type), q(e.tracking_method), q(e.load_mode),
  String(e.bodyweight_fraction), q(e.technique), q(e.cues), q(e.default_tempo), num(e.default_rest_s), num(e.difficulty), uuidArr(e.substitute_ids), 'false', String(e.seed_version),
].join(', ')})`);

const updates = cols.filter((c) => c !== 'id' && c !== 'user_id' && c !== 'seed_key').map((c) => `${c} = excluded.${c}`).join(',\n  ');
const variations = SEED_ROWS.filter((e) => e.variation_of).map((e) => `update public.exercises set variation_of = ${q(e.variation_of)}, variation_label = ${q(e.variation_label)} where id = ${q(e.id)};`);

const sql = `-- GENERATED by scripts/gen-seed-sql.ts from src/data/seed/exercises.ts — do not edit by hand (npm run gen:seed).
-- Built-in exercise library (user_id is null). Same deterministic ids as the app's local seed. Idempotent.
insert into public.exercises (${cols.join(', ')})
values
${values.join(',\n')}
on conflict (id) do update set
  ${updates};

${variations.join('\n')}
`;
writeFileSync('supabase/migrations/20261025000002_seed_exercise_library.sql', sql);
console.log(`wrote ${SEED_ROWS.length} exercises, ${variations.length} variation links`);
