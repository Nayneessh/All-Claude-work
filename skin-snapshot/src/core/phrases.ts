export const PHRASES: Record<Lang, Dict> = { en, hi };

export function phrase(lang: Lang, key: string): string {
  const v = PHRASES[lang][key] ?? PHRASES.en[key];
  if (v === undefined) throw new Error(`missing phrase: ${key}`);
  return v;
}

/** Every key must exist in every language. Checked by a unit test and at build time. */
export function missingPhraseKeys(): { lang: Lang; key: string }[] {
  const out: { lang: Lang; key: string }[] = [];
  for (const key of Object.keys(en)) if (!(key in hi)) out.push({ lang: 'hi', key });
  for (const key of Object.keys(hi)) if (!(key in en)) out.push({ lang: 'en', key });
  return out;
}
