// Generates supabase/functions/_shared/* from the app's own tested domain code, so the reminder engine and the UI can never disagree.
// `node scripts/sync-edge-shared.mjs`        -> (re)write the files
// `node scripts/sync-edge-shared.mjs --check` -> exit 1 if they are out of date (used in CI)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const read = (p) => readFileSync(new URL(p, root), 'utf8');
const banner = '// GENERATED by scripts/sync-edge-shared.mjs from src/ — do not edit by hand.\n';
const types = read('src/domain/types.ts');
// Extracts one exported declaration (interface with balanced braces, or a one-statement type alias) from src/domain/types.ts.
const grab = (name) => {
  const m = new RegExp(`export (interface|type) ${name}\\b`).exec(types); if (!m) throw new Error('missing ' + name);
  let i = m.index;
  if (m[1] === 'type') { const end = types.indexOf(';', i); return types.slice(i, end + 1) + '\n'; }
  let depth = 0; i = types.indexOf('{', i);
  for (let j = i; j < types.length; j++) { if (types[j] === '{') depth++; else if (types[j] === '}' && --depth === 0) return types.slice(m.index, j + 1) + '\n'; }
  throw new Error('unbalanced ' + name);
};
const out = {
  'supabase/functions/_shared/time.ts': banner + read('src/lib/time.ts'),
  'supabase/functions/_shared/types.ts': banner + "import type { DateStr, TimeStr } from './time.ts';\n" + ['Difficulty', 'Repeat', 'Task', 'TaskDone', 'TaskOverride'].map(grab).join('\n'),
  'supabase/functions/_shared/recurrence.ts': banner + read('src/domain/recurrence.ts').replace("from '../lib/time'", "from './time.ts'").replace("from './types'", "from './types.ts'"),
};
let stale = false;
for (const [p, c] of Object.entries(out)) {
  const url = new URL(p, root);
  if (process.argv.includes('--check')) { if (!existsSync(url) || readFileSync(url, 'utf8') !== c) { console.error('out of date:', p); stale = true; } }
  else { mkdirSync(new URL('.', url), { recursive: true }); writeFileSync(url, c); console.log('wrote', p); }
}
process.exit(stale ? 1 : 0);
